# Erstelle eine Variable mit dem Namen preis vom Datentyp float (Kommazahl) und speichere den Wert 4.5
preis = 4.5
# Erstelle eine Variable mit dem Namen anzahl vom Datentyp int (Ganzzahl) und speichere den Wert 7
anzahl = 7
# Erstelle eine Variable mit dem Namen ergebnis vom Datentyp float (Kommazahl) und speichere das Produkt aus preis mal anzahl.
ergebnis = preis * anzahl
# Gib das Ergebnis auf dem Bildschirm aus
print("Das Ergebnis ist: ", ergebnis)
# Teile anzahl durch 2 und speichere das Ergebnis in anzahl_geteilt
anzahl_geteilt = anzahl / 2
# Gib den Wert von anzahl_geteilt auf dem Bildschirm aus
print("Das Ergebnis ist:", anzahl_geteilt)
# Teile anzahl ganzzahlig durch 2, die Nachkommastellen werden abgeschnitten
anzahl_teile_ganzahl = anzahl // 2
# Gib den Wert von anzahl_teile_ganzahl auf dem Bildschirm aus
print("Ganzzahlige Division, die Nachkommastellen werden abgeschnitten:", anzahl_teile_ganzahl)
# Berechne den Rest der Division von anzahl durch 2 (Modulo)
anzahl_Rest_division= anzahl%2

# Gib den Wert von anzahl_Rest_division auf dem Bildschirm aus
print("Rest der Division (Modulo):", anzahl_Rest_division)
